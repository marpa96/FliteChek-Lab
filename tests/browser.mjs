// Integration test for an isolated Chrome debugging session (not your normal browser).
// Start Chrome with --remote-debugging-port=9227 and a fresh --user-data-dir first.
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
const origin=process.env.FLITECHEK_TEST_URL??'http://127.0.0.1:8088/';
const list=await (await fetch('http://127.0.0.1:9227/json/list')).json();
const target=list.find(t=>t.type==='page');
const socket=new WebSocket(target.webSocketDebuggerUrl);
await new Promise((resolve,reject)=>{socket.onopen=resolve;socket.onerror=reject;});
let seq=0;const pending=new Map(),errors=[];
socket.onmessage=e=>{const m=JSON.parse(e.data);if(m.id){const p=pending.get(m.id);pending.delete(m.id);m.error?p.reject(m.error):p.resolve(m.result);}else if(m.method==='Runtime.exceptionThrown')errors.push(m.params.exceptionDetails);};
const send=(method,params={})=>new Promise((resolve,reject)=>{const id=++seq;pending.set(id,{resolve,reject});socket.send(JSON.stringify({id,method,params}));});
const evaluate=async expression=>{const r=await send('Runtime.evaluate',{expression,awaitPromise:true,returnByValue:true});if(r.exceptionDetails)throw new Error(JSON.stringify(r.exceptionDetails));return r.result.value;};
const sleep=ms=>new Promise(r=>setTimeout(r,ms));
async function wait(expression){for(let i=0;i<80;i++){if(await evaluate(expression))return;await sleep(100);}throw new Error(`Timed out: ${expression}`);}
const click=selector=>evaluate(`document.querySelector(${JSON.stringify(selector)}).click()`);
const state=()=>evaluate(`JSON.parse(localStorage.getItem('flitechek.state.v1'))`);
const check=(name,condition)=>{assert.ok(condition,name);console.log('PASS:',name);};
async function shot(name){await fs.mkdir('test-output',{recursive:true});const r=await send('Page.captureScreenshot',{format:'png'});await fs.writeFile(`test-output/${name}.png`,Buffer.from(r.data,'base64'));}
await send('Page.enable');await send('Runtime.enable');await send('Network.enable');
await send('Page.navigate',{url:'about:blank'});
await send('Storage.clearDataForOrigin',{origin:new URL(origin).origin,storageTypes:'all'});
await send('Emulation.setDeviceMetricsOverride',{width:390,height:844,deviceScaleFactor:2,mobile:true});
await send('Page.navigate',{url:origin});
await wait(`!!document.querySelector('[data-action="open"]')`);
await wait(`document.querySelector('#connection').textContent==='OFFLINE READY'`);
await shot('menu-iphone');
check('no horizontal overflow at iPhone width',await evaluate('document.documentElement.scrollWidth<=390'));
await evaluate(`Array.from(document.querySelectorAll('[data-action="open"]')).find(b=>b.textContent.includes('Before Landing')).click()`);
await wait(`!!document.querySelector('.task')`);
await shot('checklist-iphone');
await click('.task .check');
let saved=await state();const id=saved.active;
check('tap persists check immediately',Object.values(saved.runs[id].states).includes('done'));
await evaluate(`window.originalSetItem=Storage.prototype.setItem;Storage.prototype.setItem=function(){throw new DOMException('Quota full','QuotaExceededError')}`);
await click('.task.current .check');
check('failed save retains prior state and shows inline error',await evaluate(`!document.querySelector('#error').hidden`));
check('failed save does not check the item',Object.values((await state()).runs[id].states).filter(v=>v==='done').length===1);
await evaluate(`Storage.prototype.setItem=window.originalSetItem`);
await click('.task.current .pending-button');
saved=await state();check('pending item is persisted',Object.values(saved.runs[id].states).includes('pending'));
await send('Page.reload');await wait(`!!document.querySelector('.task')`);
saved=await state();check('reload restores active procedure and progress',saved.active===id&&Object.values(saved.runs[id].states).includes('done'));
await click('[data-action="options"]');await click('[data-action="edit"]');
await wait(`!!document.querySelector('[data-edit-line]')`);
await evaluate(`(()=>{const input=document.querySelector('[data-edit-line]');input.value='Prototype edited item';input.dispatchEvent(new Event('input',{bubbles:true}));})()`);
await click('[data-action="emergency"]');await click('[data-action="open"]');
saved=await state();check('emergency switches procedure and preserves normal return',saved.returnTo===id&&saved.active!==id);
await evaluate(`document.querySelector('#main').scrollTop=99999`);await sleep(300);
const emergencyScroll=await evaluate(`document.querySelector('#main').scrollTop`);await sleep(6600);
check('emergency reading position does not auto-return',Math.abs(await evaluate(`document.querySelector('#main').scrollTop`)-emergencyScroll)<5);
await click('[data-action="return-normal"]');
check('return restores previous active procedure',(await state()).active===id);
await click('[data-action="menu"]');await click('[data-action="draft"]');
check('draft survives emergency navigation',await evaluate(`document.querySelector('[data-edit-line]').value==='Prototype edited item'`));
await click('[data-action="save-draft"]');
saved=await state();check('Done adds one revision',saved.checklists.find(c=>c.id===id).revisions.length===2);
check('active run keeps original Markdown',!saved.runs[id].markdown.includes('Prototype edited item'));
await click('[data-action="resume"]');await click('[data-action="options"]');await click('[data-action="history"]');
await evaluate(`document.querySelector('details:last-of-type').open=true`);await click('[data-action="restore"]');
saved=await state();check('restore appends history instead of deleting versions',saved.checklists.find(c=>c.id===id).revisions.length===3);
await click('[data-action="resume"]');
await evaluate(`document.querySelector('#main').scrollTop=99999`);await sleep(300);
await sleep(6600);
check('normal checklist returns to current unfinished item',await evaluate(`(()=>{const r=document.querySelector('.task.current').getBoundingClientRect(),m=document.querySelector('#main').getBoundingClientRect();return r.top>=m.top-5&&r.top<m.bottom;})()`));
await click('[data-action="menu"]');await click('[data-action="setup"]');
await shot('offline-iphone');
await wait(`navigator.serviceWorker.controller!==null`);
await send('Network.emulateNetworkConditions',{offline:true,latency:0,downloadThroughput:0,uploadThroughput:0});
await send('Page.reload');await wait(`!!document.querySelector('.task')`);
check('offline reload restores app and active checklist',await evaluate(`document.querySelector('h1').textContent==='Before Landing'`));
await click('.task.current .check');
check('offline interaction still saves',!!(await state()).runs[id]);
await send('Network.emulateNetworkConditions',{offline:false,latency:0,downloadThroughput:-1,uploadThroughput:-1});
const backup=await state();
await click('[data-action="menu"]');
const imported='# Imported test\n\n- [ ] First imported item\n\n<img src=x onerror="window.injected=true">\n';
await fs.writeFile('test-output/import.md',imported);
let doc=await send('DOM.getDocument');
let input=await send('DOM.querySelector',{nodeId:doc.root.nodeId,selector:'#import'});
await send('DOM.setFileInputFiles',{nodeId:input.nodeId,files:[path.resolve('test-output/import.md')]});
await wait(`document.querySelector('#edit-title')?.value==='Imported test'`);
check('Markdown import opens editable draft',(await state()).draft.markdown===imported);
check('imported HTML is inert text',await evaluate(`!window.injected&&!document.querySelector('#main img')`));
await click('[data-action="save-draft"]');
check('import adds independent checklist',(await state()).checklists.length===backup.checklists.length+1);
await click('[data-action="setup"]');
await fs.writeFile('test-output/backup.json',JSON.stringify(backup));
doc=await send('DOM.getDocument');input=await send('DOM.querySelector',{nodeId:doc.root.nodeId,selector:'#backup-import'});
await send('DOM.setFileInputFiles',{nodeId:input.nodeId,files:[path.resolve('test-output/backup.json')]});
await wait(`!!document.querySelector('[data-action="restore-backup"]')`);
await click('[data-action="restore-backup"]');
check('full backup restore returns prior library and progress',JSON.stringify(await state())===JSON.stringify(backup));
check('no uncaught browser exceptions',errors.length===0);
socket.close();
console.log('Browser integration checks complete.');
